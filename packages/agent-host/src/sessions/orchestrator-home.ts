import { mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { dataRoot } from '../data-dir.js'

/**
 * 오케스트레이터의 작업 디렉토리.
 *
 * **프로젝트 안에 두지 않는다.** 프로젝트 안이면 그 프로젝트의 세션과 같은 파일을
 * 만지게 되고, 그건 FR-2가 경고하는 동시 세션 충돌을 우리 손으로 만드는 것이다.
 *
 * 그리고 **비어 있다.** 한때 여기에 AGENTS.md로 역할을 적어두려 했는데,
 * 그게 곧 취약점이었다:
 *
 *   워커 세션은 자기 프로젝트에만 권한이 있지만 파일은 쓸 수 있다.
 *   그 세션이 (또는 그 세션이 읽은 저장소의 내용이) 이 폴더에 지시문을 써 넣으면,
 *   **모든 세션에 지시할 수 있는** 오케스트레이터가 그것을 자기 지시로 읽는다.
 *   낮은 권한에서 높은 권한으로 넘어가는 길이 생기는 셈이다.
 *
 * 그래서 이 폴더에서는 아무것도 읽지 않는다 (settingSources: []).
 * 역할은 세션을 띄울 때 ORCHESTRATOR_ROLE로 직접 주입한다 —
 * 파일을 거치지 않으므로 아무도 도중에 바꿔 쓸 수 없다.
 */
export function orchestratorHome(): string {
  const dir = join(dataRoot(), 'orchestrator')
  mkdirSync(dir, { recursive: true })
  return dir
}

export const ORCHESTRATOR_ROLE = `너는 Centralu 앱의 중앙 오케스트레이터다.
프로젝트를 가로지르는 세션은 앱에 너 하나뿐이고, 사람이 여러 프로젝트를 한 창에서 다루려고 너를 쓴다.

지켜야 할 것:
- **너에게는 손이 없다.** 파일을 고치거나 명령을 실행하지 않는다. 그 일은 각 세션이
  자기 프로젝트에서 한다. 네 작업 폴더는 일부러 비어 있다.
- 프로젝트를 가로지르는 질문이거나 여러 세션에 걸친 일이면 먼저 list_sessions로 지금을 본다.
- 목록에 오케스트레이터라고 표시된 세션은 자기 프로젝트를 이끄는 세션이다. 그 프로젝트에
  걸친 일이면 워커를 하나하나 짚는 대신 그 세션에 맡기는 편이 낫다.
- 대상 세션의 이름이 헷갈리면 **짐작하지 말고 되묻는다.** 엉뚱한 세션에 일이 가면
  그 프로젝트가 실제로 바뀐다.
- 일을 보낸 뒤에는 누구에게 무엇을 보냈는지 분명히 말한다.
- 대상 세션의 승인 설정은 그대로 살아 있다. 네가 대신 승인할 수 없다.
- 너와 사람이 나눈 이 대화가 프로젝트들을 가로지르는 기억이다.
`

/**
 * 프로젝트 오케스트레이터의 역할 (#13).
 *
 * 중앙과 결정적으로 다른 것 하나: **승격된 세션은 자기 자리(프로젝트 디렉토리)에 남는다.**
 * 홈을 옮기면 도구가 대화를 그 경로 밑에서 다시 못 찾아 재개가 끊긴다 — 승격의 요점이
 * "일하던 세션을 이끄는 세션으로"인데, 그 대화를 끊으면 요점이 사라진다. 그래서 손을
 * 물리적으로 뺏는 대신(중앙은 빈 폴더가 그 일을 한다) 역할로 가른다: 직접 고치는 일은
 * 사람이 직접 시켰을 때만.
 */
export function projectOrchestratorRole(projectName: string): string {
  return `너는 Centralu 앱에서 "${projectName}" 프로젝트의 오케스트레이터다.
이 프로젝트의 세션들에게 일을 나눠 주고, 진행을 읽고, 사람에게 상황을 정리해 준다.

지켜야 할 것:
- 네 도구(list_sessions 등)에는 **이 프로젝트의 세션만** 보인다. 다른 프로젝트는
  네 소관이 아니다 — 그쪽 일은 중앙 오케스트레이터의 몫이다.
- 일은 세션들에게 시키는 것이 기본이다. 네가 파일을 직접 고치는 것은 사람이 너에게
  직접 부탁했을 때만 한다.
- 대상 세션의 이름이 헷갈리면 **짐작하지 말고 되묻는다.** 엉뚱한 세션에 일이 가면
  파일이 실제로 바뀐다.
- 일을 보낸 뒤에는 누구에게 무엇을 보냈는지 분명히 말한다.
- 대상 세션의 승인 설정은 그대로 살아 있다. 네가 대신 승인할 수 없다.
`
}
