/**
 * Keeps only **the words a person typed** of a loaded conversation. Both tools inject system text into user turns (measured:
 * a title read `<system_instruction>You are working inside…`, a first message `<ide_opened_file>…`). **Only the block is
 * stripped**, since a real message often follows it; a line is dropped only if nothing is left after stripping.
 */

import { stripMailWakes } from '../mail/wake-text.js'

/** The wrappers a machine injects into a user turn. Identified by the name of the opening tag */
const INJECTED_TAGS = [
  'system-reminder',
  'system_instruction',
  'ide_opened_file',
  'ide_selection',
  'command-name',
  'command-message',
  'command-args',
  'local-command-stdout',
  'local-command-stderr',
  'user-prompt-submit-hook',
  /*
   * Claude Code's notice that a background task ended (#2323). A Claude transcript says who wrote such a line
   * (claude/history.ts `writtenByTheCli`); the tag is for a line read without that, from an SDK or CLI that does not give it
   */
  'task-notification',
]

const BLOCK = new RegExp(`<(${INJECTED_TAGS.join('|')})\\b[^>]*>[\\s\\S]*?</\\1>`, 'gi')
/** Some are opened without a closing tag — everything from that point on is treated as machine text */
const OPEN_ONLY = new RegExp(`<(${INJECTED_TAGS.join('|')})\\b[^>]*>[\\s\\S]*$`, 'i')
const BARE = new RegExp(`</?(${INJECTED_TAGS.join('|')})\\b[^>]*/?>`, 'gi')

const CAVEAT = /^Caveat: The messages below were generated by the user.*$/gim

/** The person's words left after the injected blocks are stripped; empty when nothing is left (the caller drops that line) */
export function stripInjectedBlocks(text: string): string {
  // Before the reminders: a mail wake is a reminder with the messages behind it, and what is left of it after the reminder is gone
  // would read as the person's words (§9.2)
  return stripMailWakes(text)
    .replace(BLOCK, '')
    .replace(OPEN_ONLY, '')
    .replace(BARE, '')
    .replace(CAVEAT, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** A one-line title for a list: the first line is enough to recognize which conversation this was */
export function cleanTitle(raw: string, max = 80): string {
  const first = stripInjectedBlocks(raw)
    .split('\n')
    .map((l) => l.trim())
    .find((l) => l.length > 0)
  if (!first) return ''
  return first.length > max ? `${first.slice(0, max - 1)}…` : first
}
