import { describe, expect, it, afterEach } from 'vitest'
import {
  __setSessionApiForTest,
  listClaudeSessions,
  readClaudeHistory,
  UNSUPPORTED as CLAUDE_UNSUPPORTED,
} from './claude/history.js'
import {
  isUnknownMethod,
  threadListToSummaries,
  turnsToHistory,
  UNSUPPORTED as CODEX_UNSUPPORTED,
} from './codex/history.js'
import { cleanTitle, stripInjectedBlocks } from './history-text.js'

/**
 * 이전 세션 불러오기는 **각 도구의 공식 API**로만 읽는다 (트랜스크립트 파일 파싱 금지).
 * 그래서 여기서 지켜야 할 것은 두 가지다:
 *   1. 응답을 대화로 옮기는 변환이 맞는가
 *   2. 구버전 도구를 만났을 때 **터지지 않고** 이유를 남기며 물러나는가
 */

afterEach(() => __setSessionApiForTest(undefined))

describe('claude — SDK listSessions/getSessionMessages', () => {
  it('목록을 요약으로 옮긴다 (제목 우선순위: 사용자 지정 → 요약 → 첫 프롬프트)', async () => {
    __setSessionApiForTest({
      listSessions: async () => [
        { sessionId: 'a', customTitle: '리팩터링', summary: 's', firstPrompt: 'f', lastModified: 1000, gitBranch: 'main' },
        { sessionId: 'b', summary: '요약만 있음', lastModified: 2000 },
        { sessionId: 'c', firstPrompt: '첫 프롬프트만', lastModified: 3000, createdAt: 500 },
        { sessionId: 'd', lastModified: 4000 },
        { summary: 'id가 없으면 버린다' },
      ],
    })
    const out = await listClaudeSessions('/p', 10)
    expect(out.map((s) => [s.externalId, s.title])).toEqual([
      ['a', '리팩터링'],
      ['b', '요약만 있음'],
      ['c', '첫 프롬프트만'],
      ['d', '제목 없는 세션'],
    ])
    expect(out[0]).toMatchObject({ updatedAt: 1000, branch: 'main' })
    expect(out[2]!.createdAt).toBe(500)
  })

  it('대화만 남긴다 — 도구 결과는 버리고 도구 호출은 이름만 남긴다', async () => {
    __setSessionApiForTest({
      listSessions: async () => [],
      getSessionMessages: async () => [
        { type: 'user', message: { content: [{ type: 'text', text: '빌드 고쳐줘' }] } },
        { type: 'assistant', message: { content: [{ type: 'tool_use', name: 'Bash', id: 'x' }] } },
        { type: 'user', message: { content: [{ type: 'tool_result', content: 'exit 0' }] } },
        { type: 'assistant', message: { content: [{ type: 'text', text: '고쳤습니다' }] } },
        { type: 'system', message: { content: 'compact boundary' } },
      ],
    })
    expect(await readClaudeHistory('s', '/p', 100)).toEqual([
      { role: 'user', text: '빌드 고쳐줘' },
      { role: 'assistant', text: '`Bash`' },
      { role: 'assistant', text: '고쳤습니다' },
    ])
  })

  it('도구가 끼워 넣은 블록은 걷어내고 사람의 말만 남긴다', async () => {
    __setSessionApiForTest({
      listSessions: async () => [],
      getSessionMessages: async () => [
        { type: 'user', message: { content: '<command-name>/clear</command-name>' } },
        { type: 'user', message: { content: '<local-command-stdout>ok</local-command-stdout>' } },
        { type: 'user', message: { content: 'Caveat: The messages below were generated by the user' } },
        { type: 'user', message: { content: '<ide_opened_file>a.ts</ide_opened_file>\n\n이것도 봐줘' } },
        { type: 'user', message: { content: '진짜 내 말' } },
      ],
    })
    expect(await readClaudeHistory('s', '/p', 100)).toEqual([
      { role: 'user', text: '이것도 봐줘' },
      { role: 'user', text: '진짜 내 말' },
    ])
  })

  it('구버전 SDK(함수 없음)는 예외 대신 이유를 남긴다', async () => {
    __setSessionApiForTest(null)
    await expect(listClaudeSessions('/p', 10)).rejects.toThrow(CLAUDE_UNSUPPORTED)
    await expect(readClaudeHistory('s', '/p', 10)).rejects.toThrow(CLAUDE_UNSUPPORTED)
  })

  it('응답이 배열이 아니어도 무너지지 않는다', async () => {
    __setSessionApiForTest({
      listSessions: async () => null as never,
      getSessionMessages: async () => undefined as never,
    })
    expect(await listClaudeSessions('/p', 10)).toEqual([])
    expect(await readClaudeHistory('s', '/p', 10)).toEqual([])
  })
})

describe('codex — thread/list · thread/read', () => {
  it('스레드 목록을 요약으로 옮긴다 (초 단위 시각 → ms)', () => {
    const out = threadListToSummaries(
      [
        { id: 't1', preview: '테스트 고치기', updatedAt: 1_700_000_000, createdAt: 1_699_999_000, cwd: '/p' },
        { id: 't2', recencyAt: 1_700_000_500, cwd: '/p' },
        { id: 't3', preview: '다른 폴더', cwd: '/other' }, // 서버가 안 걸렀어도 우리가 거른다
        { preview: 'id 없음', cwd: '/p' },
      ],
      '/p',
    )
    expect(out).toEqual([
      { externalId: 't1', title: '테스트 고치기', updatedAt: 1_700_000_000_000, createdAt: 1_699_999_000_000 },
      { externalId: 't2', title: '제목 없는 세션', updatedAt: 1_700_000_500_000, createdAt: undefined },
    ])
  })

  it('turns에서 사람과 모델의 말만 뽑는다 — 모르는 항목은 조용히 흘린다', () => {
    const out = turnsToHistory(
      [
        {
          startedAt: 1_700_000_000,
          items: [
            { type: 'userMessage', content: [{ type: 'input_text', text: '테스트 돌려줘' }] },
            { type: 'reasoning', summary: [], content: [] },
            { type: 'commandExecution', command: 'pnpm test' },
            { type: 'agentMessage', text: '전부 통과했습니다' },
            { type: '앞으로_생길_새_항목', text: '몰라도 터지지 않는다' },
          ],
        },
      ],
      100,
    )
    expect(out).toEqual([
      { role: 'user', text: '테스트 돌려줘', ts: 1_700_000_000_000 },
      { role: 'assistant', text: '전부 통과했습니다', ts: 1_700_000_000_000 },
    ])
  })

  it('한도를 넘으면 최근 대화를 남긴다 (오래된 쪽을 자른다)', () => {
    const turns = [
      {
        items: Array.from({ length: 10 }, (_, i) => ({ type: 'agentMessage', text: `m${i}` })),
      },
    ]
    expect(turnsToHistory(turns, 3).map((m) => m.text)).toEqual(['m7', 'm8', 'm9'])
  })

  it('turns가 없거나 이상해도 빈 대화를 준다', () => {
    expect(turnsToHistory(undefined, 10)).toEqual([])
    expect(turnsToHistory([null, { items: 'not an array' }], 10)).toEqual([])
    expect(threadListToSummaries(undefined, '/p')).toEqual([])
  })

  it('구버전 codex의 "모르는 메서드" 응답을 알아본다', () => {
    expect(isUnknownMethod(new Error('Method not found'))).toBe(true)
    expect(isUnknownMethod(new Error('JSON-RPC error -32601'))).toBe(true)
    expect(isUnknownMethod(new Error('unknown method thread/list'))).toBe(true)
    // 진짜 고장은 '지원 안 함'으로 감추면 안 된다 — 그래야 사용자가 원인을 본다
    expect(isUnknownMethod(new Error('EACCES: permission denied'))).toBe(false)
    expect(CODEX_UNSUPPORTED).toMatch(/업데이트/)
  })
})

describe('주입된 블록 걷어내기 (실측: 제목이 <system_instruction>으로 나왔다)', () => {
  it('블록만 걷어내고 뒤에 이어진 사람의 말은 남긴다', () => {
    expect(
      stripInjectedBlocks('<ide_opened_file>The user opened /a/b.ts</ide_opened_file>\n\n이 파일 고쳐줘'),
    ).toBe('이 파일 고쳐줘')
    expect(stripInjectedBlocks('앞말\n<system-reminder>배경 정보</system-reminder>\n뒷말')).toBe('앞말\n\n뒷말')
  })

  it('닫는 태그가 없으면 그 지점부터 끝까지 기계 텍스트로 본다', () => {
    expect(stripInjectedBlocks('진짜 질문\n<system_instruction>\nYou are working inside…')).toBe('진짜 질문')
  })

  it('걷어내고 남는 게 없으면 빈 문자열 — 호출자가 그 줄을 버린다', () => {
    expect(stripInjectedBlocks('<command-name>/clear</command-name>')).toBe('')
    expect(stripInjectedBlocks('Caveat: The messages below were generated by the user')).toBe('')
  })

  it('제목은 걷어낸 뒤 첫 줄만, 길면 자른다', () => {
    expect(cleanTitle('<system_instruction>You are working inside Conductor</system_instruction>\n워크트리 질문')).toBe(
      '워크트리 질문',
    )
    expect(cleanTitle('a'.repeat(200), 10)).toBe(`${'a'.repeat(9)}…`)
    expect(cleanTitle('<command-name>/clear</command-name>')).toBe('')
  })

  it('모델이 실제로 쓴 꺾쇠 텍스트는 건드리지 않는다', () => {
    expect(stripInjectedBlocks('<div>이건 코드 얘기</div>')).toBe('<div>이건 코드 얘기</div>')
  })
})
