/**
 * M4 C-1: 앱 템플릿이 들고 다니는 런타임을 만든다 — `node server.mjs`가 `npm install` 없이 뜨는 이유다.
 *
 *   pnpm build:app-runtime            다시 만들어 app-template/runtime/에 쓴다
 *   pnpm build:app-runtime --check    새로 만든 것이 커밋된 것과 바이트까지 같은지만 본다 (테스트가 부른다)
 *
 * 산출물 (packages/agent-host/app-template/runtime/):
 *   centralu-app-runtime.mjs       서버 SDK v2 + zod + MCP Apps 서버 도우미 + `centralu` (ESM, 압축)
 *   centralu-app-runtime.mjs.map   위의 소스맵 — 압축한 런타임 안의 스택을 읽을 수 있게 (S-6)
 *   mcp-app.js                     화면 쪽 브리지(ext-apps `App`) — 화면 HTML에 끼워 넣는다
 *   THIRD_PARTY_LICENSES.txt       묶어 넣은 모든 것의 라이선스 원문
 *
 * **같은 입력이면 같은 바이트가 나온다.** 앱마다 이 파일들이 커밋되므로(프로젝트 앱은 저장소에 산다),
 * 빌드할 때마다 달라지면 아무것도 안 바꾼 Centralu 업데이트가 모든 앱에 변경을 만든다. 그래서 시각을
 * 싣지 않고, 소스맵의 경로를 이 기계의 폴더 배치(pnpm 저장소 해시)와 무관한 이름으로 바꾸고, 판을 못 박는다.
 *
 * **판은 PINS가 정한다.** 설치된 판이 다르면 멈춘다 — 잠금 파일이 조용히 올린 판이 모든 앱의 런타임을
 * 바꾸면 안 된다. 올리는 것은 이 표를 고치는 커밋으로 한다.
 *
 * **MIT만 받는다.** 앱 폴더는 사용자의 저장소에 커밋되고 팀에 나뉜다 — 그 안에 든 제3자 코드의 조건이
 * 사용자의 저장소 조건이 된다. MIT가 아닌 것이 끼어들면 멈추고 이름을 댄다.
 */
import { build } from 'esbuild'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const HERE = dirname(fileURLToPath(import.meta.url))
const PKG = resolve(HERE, '..')
const ROOT = resolve(PKG, '../..')
const SRC = join(PKG, 'app-runtime', 'src')
const DEST = join(PKG, 'app-template', 'runtime')

/** 묶어 넣는 것과 묶는 도구의 판 — 바꾸려면 여기를 고친다 */
export const PINS = {
  esbuild: '0.28.2',
  '@modelcontextprotocol/server': '2.1.0',
  '@modelcontextprotocol/core': '2.1.0',
  '@modelcontextprotocol/client': '2.1.0',
  '@modelcontextprotocol/ext-apps': '2.0.0',
  zod: '4.4.3',
}

const RUNTIME = 'centralu-app-runtime.mjs'
const VIEW = 'mcp-app.js'
const LICENSES = 'THIRD_PARTY_LICENSES.txt'
const OUTPUTS = [RUNTIME, `${RUNTIME}.map`, VIEW, LICENSES]

const HEADER = `// GENERATED by Centralu — do not edit, format, or read in full. Replaced when Centralu updates the app runtime.
// @modelcontextprotocol/server ${PINS['@modelcontextprotocol/server']}, @modelcontextprotocol/ext-apps ${PINS['@modelcontextprotocol/ext-apps']} (server helpers), zod ${PINS.zod}, and the Centralu helper.
// Licenses: ./${LICENSES}`
const VIEW_HEADER = `/* GENERATED by Centralu — do not edit. MCP App bridge (@modelcontextprotocol/ext-apps ${PINS['@modelcontextprotocol/ext-apps']}, MIT). */`

function fail(msg) {
  console.error(`[app-runtime] ${msg}`)
  process.exit(1)
}

/**
 * `from` 폴더에서 Node가 찾는 대로 패키지 폴더를 찾는다. `require.resolve('<이름>/package.json')`은
 * 쓸 수 없다 — package.json을 exports에 싣지 않은 패키지(ext-apps)가 있다.
 */
function findPackage(name, from) {
  for (const dir of createRequire(join(from, 'package.json')).resolve.paths(name) ?? []) {
    if (existsSync(join(dir, name, 'package.json'))) return realpathSync(join(dir, name))
  }
  return null
}

/** 설치된 판이 PINS와 같은가 — 다르면 멈춘다 */
function checkPins() {
  const wrong = []
  // client·core는 agent-host가 직접 들이지 않을 수 있다 — 그것을 쓰는 패키지(ext-apps·server) 쪽에서 찾는다
  const lookIn = [PKG, findPackage('@modelcontextprotocol/ext-apps', PKG), findPackage('@modelcontextprotocol/server', PKG)].filter(Boolean)
  for (const [name, want] of Object.entries(PINS)) {
    const dir = lookIn.map((from) => findPackage(name, from)).find(Boolean)
    if (!dir) {
      wrong.push(`${name}: not installed`)
      continue
    }
    const got = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version
    if (got !== want) wrong.push(`${name}: installed ${got}, pinned ${want}`)
  }
  if (wrong.length) fail(`installed versions differ from PINS — update PINS on purpose, not by accident:\n  ${wrong.join('\n  ')}`)
}

/** node_modules 안의 파일 → 그 패키지의 폴더 (pnpm의 `.pnpm/<해시>/node_modules/<이름>`도 같은 규칙이다) */
function packageDirOf(absPath) {
  const i = absPath.lastIndexOf(`${sep}node_modules${sep}`)
  if (i < 0) return null
  const rest = absPath.slice(i + `${sep}node_modules${sep}`.length).split(sep)
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]
  return absPath.slice(0, i + `${sep}node_modules${sep}`.length) + name.split('/').join(sep)
}

/**
 * 소스맵의 경로를 이 기계와 무관한 이름으로. `vendored/<패키지>@<판>/<파일>`, 우리 것은 `vendored/centralu/<파일>`.
 * 원래 경로는 출력 폴더에서 pnpm 저장소까지의 상대 경로라, 폴더 배치가 다르면 같은 빌드가 다른 바이트가 된다.
 */
function canonicalSource(absPath) {
  const pkgDir = packageDirOf(absPath)
  /*
   * 패키지의 dist가 자기 소스맵을 싣고 있으면 esbuild는 그 원본(TS 소스)까지 거슬러 간다 — 스택이 더
   * 잘 읽히는 쪽이라 그대로 둔다. 그 원본은 디스크에 없으므로(`core-internal/src/…`) 판 없이 이름만 붙인다.
   */
  if (pkgDir && !existsSync(join(pkgDir, 'package.json'))) {
    const i = absPath.lastIndexOf(`${sep}node_modules${sep}`)
    return `vendored/${absPath.slice(i + `${sep}node_modules${sep}`.length).split(sep).join('/')}`
  }
  if (pkgDir) {
    const pj = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
    return `vendored/${pj.name}@${pj.version}/${relative(pkgDir, absPath).split(sep).join('/')}`
  }
  if (absPath.startsWith(SRC + sep)) return `vendored/centralu/${relative(SRC, absPath).split(sep).join('/')}`
  return `vendored/other/${relative(ROOT, absPath).split(sep).join('/')}`
}

async function buildInto(outDir) {
  const inputs = new Set()
  const node = await build({
    entryPoints: [join(SRC, 'index.mjs')],
    outfile: join(outDir, RUNTIME),
    bundle: true,
    platform: 'node',
    target: 'node22',
    format: 'esm',
    minify: true,
    sourcemap: 'linked',
    sourcesContent: false,
    legalComments: 'none', // 라이선스 원문은 THIRD_PARTY_LICENSES.txt에 모은다
    banner: { js: HEADER },
    metafile: true,
    logLevel: 'warning',
  })
  const view = await build({
    entryPoints: [join(SRC, 'view.mjs')],
    outfile: join(outDir, VIEW),
    bundle: true,
    platform: 'browser',
    target: 'es2022',
    format: 'iife',
    globalName: 'McpApp',
    minify: true,
    legalComments: 'none',
    banner: { js: VIEW_HEADER },
    metafile: true,
    logLevel: 'warning',
  })
  /*
   * 라이선스는 **출력에 실제로 들어간** 파일의 패키지만 센다. esbuild가 읽기만 하고 한 바이트도 싣지 않은
   * 파일(쓰지 않는 OAuth 코드의 import 등)까지 세면, 앱 폴더에 없는 코드의 라이선스를 적게 된다.
   */
  for (const m of [node.metafile, view.metafile]) {
    for (const out of Object.values(m.outputs)) {
      for (const [p, v] of Object.entries(out.inputs)) if (v.bytesInOutput > 0) inputs.add(resolve(ROOT, p))
    }
  }

  // 소스맵의 경로를 고친다 (canonicalSource)
  const mapPath = join(outDir, `${RUNTIME}.map`)
  const map = JSON.parse(readFileSync(mapPath, 'utf8'))
  const abs = map.sources.map((s) => resolve(outDir, s))
  map.sources = abs.map(canonicalSource)
  /*
   * 원문은 **우리 도우미의 것만** 싣는다(몇 KiB). 잡히지 않은 오류가 나면 Node는 던진 줄을 스택 위에 찍는데,
   * 원문이 없으면 압축된 한 줄(수백 자)을 찍어 표준에러 끝부분의 한 칸을 먹는다. 앱 작성자의 인자가 틀려
   * 나는 오류는 대개 도우미 안에서 던져진다. 제3자 코드의 원문까지 실으면 맵이 몇 MB가 된다.
   */
  map.sourcesContent = abs.map((p) => (p.startsWith(SRC + sep) ? readFileSync(p, 'utf8') : null))
  writeFileSync(mapPath, `${JSON.stringify(map)}\n`)

  writeFileSync(join(outDir, LICENSES), licenses(inputs))
}

/** 묶어 넣은 패키지들의 라이선스 — MIT가 아니면 멈춘다 */
function licenses(inputs) {
  const pkgs = new Map()
  for (const p of inputs) {
    const dir = packageDirOf(p)
    if (dir && !pkgs.has(dir)) pkgs.set(dir, JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')))
  }
  const rows = [...pkgs.entries()].sort(([, a], [, b]) => a.name.localeCompare(b.name))
  const notMit = rows.filter(([, pj]) => pj.license !== 'MIT').map(([, pj]) => `${pj.name}@${pj.version} (${JSON.stringify(pj.license ?? pj.licenses)})`)
  if (notMit.length) fail(`only MIT-licensed code may be vendored into app folders — not MIT:\n  ${notMit.join('\n  ')}`)
  let text =
    'Third-party software bundled into centralu-app-runtime.mjs and mcp-app.js.\n' +
    'Every package below is MIT-licensed (the build refuses anything else).\n'
  text += `\n\n==== Centralu app runtime helper (MIT) ====\n${readFileSync(join(ROOT, 'LICENSE'), 'utf8').trim()}\n`
  for (const [dir, pj] of rows) {
    const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f))
    text += `\n\n==== ${pj.name}@${pj.version} (${pj.license}) ====\n${file ? readFileSync(join(dir, file), 'utf8').trim() : '(the npm package ships no license file; its package.json declares MIT)'}\n`
  }
  return text
}

const kib = (n) => `${(n / 1024).toFixed(1)} KiB`

checkPins()
if (process.argv.includes('--check')) {
  const tmp = mkdtempSync(join(tmpdir(), 'cc-app-runtime-'))
  try {
    await buildInto(tmp)
    const stale = OUTPUTS.filter((f) => !existsSync(join(DEST, f)) || !readFileSync(join(tmp, f)).equals(readFileSync(join(DEST, f))))
    if (stale.length) fail(`the committed runtime is not what this source builds (${stale.join(', ')}) — run: pnpm build:app-runtime`)
    console.log(`[app-runtime] up to date: ${OUTPUTS.join(', ')}`)
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
} else {
  mkdirSync(DEST, { recursive: true })
  await buildInto(DEST)
  for (const f of OUTPUTS) {
    const buf = readFileSync(join(DEST, f))
    console.log(`[app-runtime] ${f.padEnd(32)} ${kib(buf.length).padStart(10)}  gzip ${kib(gzipSync(buf).length).padStart(10)}`)
  }
}
