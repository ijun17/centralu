import { z } from 'zod'

/**
 * A session id — an opaque identifier we generate ourselves (`randomUUID()`).
 *
 * **The reason its shape is pinned down at the protocol level is that this value becomes a path
 * segment** (#94). The attachments folder (`<data>/attachments/<id>/`) and the handoff note
 * (`<data>/handoff/<project id>/<id>.md`) use this string directly as a directory or file name.
 * Back when it was `z.string()`, sending `"../../Documents"` to `agents.deleteSession` returned
 * `{ ok: true }` while deleting that folder two levels above the data folder with
 * `recursive: true`, and `attachments.save` could create a file at any path with any extension
 * the same way. Both were measured.
 *
 * So the question is not "does this path escape somewhere," but **"is this a single segment to
 * begin with?"** Since separators, and names starting with `.`, cannot pass at all, `..` cannot
 * even be expressed — this is stronger than filtering out escaping paths, and a reader can
 * confirm it in one line. (The same logic already exists in `baseName` in `dev-services/fs.ts`:
 * wherever a name is expected, instead of checking for containment, anything that is not a name
 * is rejected outright.)
 *
 * The 128-character cap is one more filter against a value that is not an id at all — a UUID is
 * 36 characters.
 */
const SESSION_ID_RE = /^[A-Za-z0-9_-][A-Za-z0-9._-]{0,127}$/

export const SessionId = z.string().regex(SESSION_ID_RE, 'Not a session id')
export type SessionId = z.infer<typeof SessionId>

/**
 * The same judgment, in places zod cannot reach.
 *
 * The one filter at the boundary is the main defense (docs/protocol.md §4), and this is a
 * second line of defense that whatever **builds a path** sets up for itself. A function that
 * builds a path can be called without ever passing through the protocol (internal calls, or
 * future callers), and without this function there, #94 comes right back.
 */
export function isSessionId(value: string): boolean {
  return SESSION_ID_RE.test(value)
}

/**
 * A project id — pinned to a shape **for the same reason** as the session id (#132).
 *
 * This value also becomes a path segment: a worktree (`<worktree root>/<project id>/<session
 * id>`) and a handoff note (`<data>/handoff/<project id>/<session id>.md`). Back when it was
 * `z.string()`, sending `projectId: "../escaped"` with `worktree: true` to `agents.createSession`
 * created a git worktree and a branch outside the worktree root before it was even asked whether
 * the project was registered, and only failed afterward with "Project not found," leaving both
 * behind (measured).
 *
 * A project id is also generated by us via `randomUUID()` (the only place this happens is
 * `addProject`) — all 7 projects in real usage data were 36-character UUIDs too. So this reuses
 * the session id's judgment as-is: the question is not containment, but **"is this a single
 * segment to begin with?"**
 */
export const ProjectId = z.string().regex(SESSION_ID_RE, 'Not a project id')
export type ProjectId = z.infer<typeof ProjectId>

/** The same judgment, in places zod cannot reach — a second line of defense for whatever builds a path (the same as `isSessionId`) */
export function isProjectId(value: string): boolean {
  return SESSION_ID_RE.test(value)
}

/**
 * A tool's identifier — open, not a fixed list.
 *
 * This was `z.enum(['claude', 'codex'])`, which meant every vendor had to be taught to
 * this package before an adapter for it could exist: a third tool could not be added
 * without editing a file two layers away from the only code that knows anything about
 * it. The set of tools is now whatever the host has adapters for, and it travels over
 * the wire rather than being compiled in on both sides.
 */
export const ToolName = z.string().min(1)
export type ToolName = z.infer<typeof ToolName>

/**
 * An app's identifier — an open string rather than a closed list (M4 P-1).
 *
 * The UI used to hold this as a union of exactly one, `'control'`. That was true while there was
 * only one compiled-in app, but an app discovered at runtime (an external app under M4) has a
 * name that cannot be known at build time — a closed union leaves the type with no room to
 * enroll such an app in the roster at all. The same move as opening up `ToolName` above (#74):
 * which apps exist is a fact the host knows, not a fact the compiler knows.
 *
 * The wire was open from the start (`apps.*`'s appId was already `z.string()`). Only the UI's
 * type was closed, so no character or length rule is added here — receiving whatever value
 * arrives now, unchanged, is what keeps behavior the same. The character rule for an external
 * app's id is decided where the manifest is validated (A-1).
 */
export const AppId = z.string()
export type AppId = z.infer<typeof AppId>

/**
 * Permission preset — overrides the CLI's global setting on a per-session basis (validated at M0). In rank order,
 * lowest first. `edits` (#1525) is `normal` plus edits inside the session's folder without a card.
 */
export const PermissionPreset = z.enum(['safe', 'normal', 'edits', 'auto'])
export type PermissionPreset = z.infer<typeof PermissionPreset>
